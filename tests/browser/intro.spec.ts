import { test, expect } from '@playwright/test';

test('signature intro scrolls reversibly beneath the collection', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto('/');
  const intro = page.locator('.gallery-intro');
  const signature = page.locator('.intro-signature');
  const collection = page.locator('#collection');
  const cursor = page.locator('.intro-cursor');
  await expect(signature).toHaveText('asciibase64');
  await expect(signature).toHaveCSS('opacity', '1');
  await expect(cursor).toHaveAttribute('aria-hidden', 'true');
  await expect(cursor).toHaveCSS('animation-duration', '1.4s');
  expect(await collection.evaluate(element => element.getBoundingClientRect().top)).toBe(900);
  expect(await page.locator('.site-header').evaluate(element => element.getBoundingClientRect().top)).toBe(900);
  await page.evaluate(() => document.fonts.ready);
  await expect(intro).toHaveCSS('background-color', 'rgb(11, 13, 16)');
  await expect(signature).toHaveCSS('color', 'rgb(214, 217, 221)');
  await expect(cursor).toHaveCSS('background-color', 'rgb(170, 177, 186)');
  await expect(page.getByRole('heading', { level: 1, name: 'asciibase64', exact: true })).toHaveCount(1);
  await expect(page.locator('.intro-art')).toHaveAttribute('aria-hidden', 'true');
  await page.screenshot({ path: info.outputPath('intro-desktop.png') });
  await page.evaluate(() => window.scrollTo(0, 292));
  await expect.poll(() => signature.evaluate(element => Number(getComputedStyle(element).opacity))).toBeCloseTo(.5, 2);
  await expect(page.locator('.intro-explore')).toHaveCSS('opacity', '0');
  expect(await intro.evaluate(element => element.getBoundingClientRect().top)).toBe(0);
  expect(await collection.evaluate(element => element.getBoundingClientRect().top)).toBe(608);
  await expect(signature).toHaveCSS('transform', 'none');
  await expect(page.locator('.intro-light')).toHaveCSS('transform', 'none');
  await page.screenshot({ path: info.outputPath('intro-transition.png') });
  await page.evaluate(() => window.scrollTo(0, 900));
  await expect(intro).toHaveAttribute('data-covered', 'true');
  await expect(cursor).toHaveCSS('animation-play-state', 'paused');
  await expect(signature).toHaveCSS('opacity', '0');
  expect(await page.locator('.site-header').evaluate(element => element.getBoundingClientRect().top)).toBe(0);
  await page.screenshot({ path: info.outputPath('intro-collection.png') });
  await page.evaluate(() => window.scrollTo(0, 0));
  await expect(signature).toHaveCSS('opacity', '1');
  await expect(cursor).toHaveCSS('animation-play-state', 'running');
  await expect(signature).toHaveCSS('transform', 'none');
  await page.keyboard.press('Tab');
  await expect(page.getByRole('link', { name: '探索簡報' })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page).toHaveURL(/#collection$/);
  await expect(page.locator('#collection-title')).toBeFocused();
  await expect.poll(() => collection.evaluate(element => element.getBoundingClientRect().top)).toBe(0);
  expect(await page.evaluate(() => sessionStorage.length)).toBe(0);
});

test('intro supports mobile, reduced motion, direct links and scroll restoration', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  for (const viewport of [{ width: 390, height: 844 }, { width: 768, height: 1024 }, { width: 320, height: 568 }]) {
    await page.setViewportSize(viewport);
    await page.goto('/');
    const signature = page.locator('.intro-signature');
    await expect(signature).toHaveCSS('opacity', '1');
    await expect(page.locator('.intro-cursor')).toHaveCSS('animation-name', 'none');
    expect(await page.locator('.intro-light').evaluate(element => getComputedStyle(element, '::before').clipPath)).toBe(viewport.width <= 700 ? 'polygon(90% 0px, 100% 0px, 100% 100%, 78% 100%)' : 'polygon(72% 0px, 100% 0px, 100% 100%, 58% 100%)');
    const bounds = await signature.boundingBox();
    expect(bounds!.x).toBeGreaterThan(0);
    expect(bounds!.x + bounds!.width).toBeLessThan(viewport.width);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath(`intro-${viewport.width}.png`) });
    await page.getByRole('link', { name: '探索簡報' }).click();
    await expect(page.locator('#collection-title')).toBeFocused();
    await expect(page.locator('.gallery-intro')).toHaveAttribute('data-covered', 'true');
    await expect(signature).toHaveCSS('opacity', '1');
    await expect(signature).toHaveCSS('transform', 'none');
    await expect(page.locator('.intro-light')).toHaveCSS('transform', 'none');
  }
  await page.goto('/#collection');
  await expect.poll(() => page.locator('#collection').evaluate(element => element.getBoundingClientRect().top)).toBe(0);
  await page.evaluate(() => window.scrollBy(0, 180));
  const position = await page.evaluate(() => scrollY);
  await page.reload();
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(position);
  await page.goto('/template?start=1');
  await expect(page.locator('.page-incoming')).toBeVisible();
  await page.goBack();
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(position);
  await expect(page.locator('.gallery-intro')).toHaveAttribute('data-covered', 'true');
});

test('architectural background stays still and only the cursor animates', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto('/');
  const art = page.locator('.intro-art');
  const signature = page.locator('.intro-signature');
  await expect(signature).toHaveText('asciibase64');
  await expect(signature).toHaveCSS('opacity', '1');
  await expect(page.locator('.intro-overprint, .intro-panel, .intro-letterform')).toHaveCount(0);
  await expect(art).toHaveCSS('pointer-events', 'none');
  const bounds = await art.boundingBox();
  expect(await page.locator('.gallery-intro').evaluate(element => element.getAnimations({ subtree: true }).map(animation => (animation as CSSAnimation).animationName))).toEqual(['signature-blink']);
  await page.evaluate(() => window.scrollTo(0, innerHeight * .3));
  await expect.poll(() => page.locator('.intro-signature').evaluate(element => Number(getComputedStyle(element).opacity))).toBeLessThan(1);
  expect(await art.boundingBox()).toEqual(bounds);
  await expect(signature).toHaveCSS('transform', 'none');
  await page.evaluate(() => window.scrollTo(0, 0));
  await expect(page.locator('.intro-signature')).toHaveCSS('opacity', '1');
  expect(await art.evaluate(element => element.getAnimations({ subtree: true }).length)).toBe(0);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  expect(await page.locator('.gallery-intro').evaluate(element => element.getAnimations({ subtree: true }).length)).toBe(0);
});
