import { test, expect } from '@playwright/test';

test('the public template appears as a second animated showcase with static previews', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto('/');
  const card = page.locator('[data-gallery-deck="template"]');
  await card.getByRole('heading', { name: 'Template', exact: true }).scrollIntoViewIfNeeded();
  await expect(card.locator('.slide-preview')).toHaveCount(9);
  await expect(card.locator('.deck-meta')).toHaveText('7 頁');
  await expect(card.locator('.deck-surface')).toHaveCSS('opacity', '1');
  await expect(card.locator('.template-slide button')).toHaveCount(0);
  expect(await card.locator('.mosaic-grid').evaluate(element => element.getAnimations({ subtree: true }).filter(animation => animation.playState === 'running').length)).toBe(0);
  expect(await page.evaluate(() => sessionStorage.length)).toBe(0);
  await page.screenshot({ path: info.outputPath('template-showcase.png') });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await card.getByRole('link', { name: '播放投影片', exact: true }).click();
  await expect(page).toHaveURL(/\/template$/);
  await expect(page.locator('.page-incoming [data-template-slide]')).toHaveAttribute('data-template-slide', 'cover');
});

test('template supports independent themes, reversible steps, custom transitions and restart', async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.goto('/template?start=1');
  const slide = page.locator('.page-incoming [data-template-slide]');
  await expect(slide).toHaveAttribute('data-template-slide', 'cover');
  await expect(slide).toHaveCSS('background-color', 'rgb(233, 229, 255)');
  await page.keyboard.press('ArrowRight');
  await expect(slide).toHaveAttribute('data-step', '1');
  await page.keyboard.press('o');
  await page.locator('[data-target="motion"]').click();
  await expect(slide).toHaveAttribute('data-template-slide', 'motion');
  await expect(slide).toHaveCSS('background-color', 'rgb(24, 28, 47)');
  await expect(page.locator('.page-transition')).toHaveAttribute('data-transition', 'template-slide');
  await expect(page.locator('.page-transition')).toHaveAttribute('data-transition', 'none');
  const shape = slide.locator('.template-motion-shape');
  const pose = () => shape.evaluate(element => {
    const matrix = new DOMMatrixReadOnly(getComputedStyle(element).transform);
    return { x: matrix.e, rotation: Math.atan2(matrix.b, matrix.a) * 180 / Math.PI };
  });
  await expect.poll(async () => (await pose()).x).toBeCloseTo(-100, 1);
  await slide.getByRole('button', { name: '下一步 →' }).click();
  await expect.poll(async () => (await pose()).x).toBeCloseTo(100, 1);
  await page.keyboard.press('ArrowRight');
  await expect.poll(async () => (await pose()).rotation).toBeCloseTo(135, 1);
  await page.screenshot({ path: info.outputPath('template-motion.png') });
  await page.keyboard.press('ArrowLeft');
  await expect.poll(async () => (await pose()).rotation).toBeCloseTo(0, 1);
  await page.reload();
  await expect(slide).toHaveAttribute('data-template-slide', 'motion');
  await expect(slide).toHaveAttribute('data-step', '1');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.keyboard.press('ArrowRight');
  await expect(slide).toHaveAttribute('data-still', 'true');
  await expect.poll(async () => (await pose()).rotation).toBeCloseTo(135, 1);
  expect(await slide.evaluate(element => element.getAnimations({ subtree: true }).filter(animation => animation.playState === 'running').length)).toBe(0);
  await page.keyboard.press('PageDown');
  await expect(slide).toHaveAttribute('data-template-slide', 'closing');
  await slide.getByRole('button', { name: '重新體驗 →' }).click();
  await expect(slide).toHaveAttribute('data-template-slide', 'cover');
  await expect(slide).toHaveAttribute('data-step', '0');
  expect(await page.evaluate(() => sessionStorage.getItem('slides:backend-workshop:progress'))).toBeNull();
});
